import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { parse } from "yaml";

const outputRoot = process.env.PROTOCOL_OUTPUT_ROOT ?? ".";
const schemaDirectory = join(outputRoot, "protocol/schema/json");
const schemaOutput = join(schemaDirectory, "openapi.bundle.json");
const eventOutput = join(schemaDirectory, "events.bundle.json");
const sources = [["contracts/openapi.yaml", schemaOutput], ["contracts/events.yaml", eventOutput]];
const documents = await Promise.all(sources.map(async ([source, output]) => ({
  source,
  output,
  document: parse(await readFile(source, "utf8")),
})));

const openapi = documents.find(({ source }) => source.endsWith("openapi.yaml"))?.document;
if (openapi?.openapi !== "3.1.0") {
  throw new Error(`expected OpenAPI 3.1.0, received ${openapi?.openapi ?? "missing"}`);
}
const events = documents.find(({ source }) => source.endsWith("events.yaml"))?.document;
if (events?.$schema !== "https://json-schema.org/draft/2020-12/schema") {
  throw new Error("events contract must declare JSON Schema draft 2020-12");
}
if (!events?.$id || !Array.isArray(events?.required) || !events.required.includes("specversion")) {
  throw new Error("events contract must be a self-identifying CloudEvents envelope schema");
}

await rm(schemaDirectory, { recursive: true, force: true });
await mkdir(schemaDirectory, { recursive: true });
for (const { output, document } of documents) {
  await writeFile(output, `${JSON.stringify(document, null, 2)}\n`);
}

const generator = "node_modules/@hey-api/openapi-ts/bin/run.js";
const result = spawnSync(process.execPath, [generator, "-f", "openapi-ts.config.mjs"], {
  encoding: "utf8",
  shell: false,
  stdio: "inherit",
  env: { ...process.env, PROTOCOL_OUTPUT_ROOT: outputRoot },
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

const eventTypes = events.properties?.type?.enum;
if (!Array.isArray(eventTypes) || eventTypes.length === 0 || eventTypes.some((type) => typeof type !== "string")) {
  throw new Error("events contract must declare a non-empty string type registry");
}
const eventTypeUnion = eventTypes.map((type) => `  | ${JSON.stringify(type)}`).join("\n");
const eventTypesOutput = join(outputRoot, "packages/api-client/src/generated/events.gen.ts");
await mkdir(join(outputRoot, "packages/api-client/src/generated"), { recursive: true });
await writeFile(eventTypesOutput, `// This file is auto-generated by scripts/generate-protocol.mjs\n\nexport type EventType =\n${eventTypeUnion};\n\nexport interface CloudEventEnvelope<TData extends Record<string, unknown> = Record<string, unknown>> {\n  specversion: "1.0";\n  id: string;\n  type: EventType;\n  source: "urn:sumi:voice-crm/crm";\n  subject: string;\n  time: string;\n  datacontenttype: "application/json";\n  tenant_id: string;\n  request_id: string;\n  traceparent?: string;\n  data: TData;\n}\n`);

console.log(`protocol generated from ${documents.map(({ source }) => source).join(", ")}`);
